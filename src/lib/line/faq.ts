export function matchFaq(text: string): string | null {
  const t = (text || "").toLowerCase().replace(/\s/g, "");
  let best: { a: string; score: number } | null = null;
  for (const f of FAQS) {
    for (const k of f.k) {
      if (t.includes(k.toLowerCase())) {
        const score = k.length; // 比較長的關鍵字優先（較精準）
        if (!best || score > best.score) best = { a: f.a, score };
      }
    }
  }
  return best?.a ?? null;
}
