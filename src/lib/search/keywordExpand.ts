const STOP = new Set(["補助", "申請", "服務", "中心", "課程", "專線", "資源", "活動", "費用", "資訊", "諮詢", "預約"]);

// 由口語關鍵字 → 對應的細標籤名稱（精準）＋命中的口語詞（給名稱/摘要 ilike 補強）
export function expandKeyword(keyword: string): { subcatNames: string[]; terms: string[] } {
  const kw = nz(keyword);
  if (kw.length < 2) return { subcatNames: [], terms: [] };
  const subs = new Set<string>();
  const terms = new Set<string>();
  const kwNoStop = STOP.has(kw);
  for (const e of SUBCAT_SYNONYMS) {
    for (const t of e.terms) {
      const nt = nz(t);
      if (nt.length < 2) continue;
      // 正向：口語詞出現在使用者輸入中（精準）
      // 反向：使用者輸入是口語詞的一部分（例「救護」→「救護車」），但排除太通用的詞
      const hit = kw.includes(nt) || (!kwNoStop && nt.includes(kw));
      if (hit) { subs.add(e.subcat); terms.add(t); break; }
    }
  }
  return { subcatNames: [...subs], terms: [...terms] };
}
